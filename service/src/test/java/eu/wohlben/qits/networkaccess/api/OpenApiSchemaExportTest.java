package eu.wohlben.qits.networkaccess.api;

import static io.restassured.RestAssured.given;

import io.quarkus.test.junit.QuarkusTest;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import org.eclipse.microprofile.config.inject.ConfigProperty;
import org.junit.jupiter.api.Test;

/**
 * Writes {@code docs/openapi.yml} as a side effect of the suite: an API change becomes a reviewable
 * diff, and it is the document the platform's golden-master coverage check reads (every operation
 * needs a golden master). It asserts nothing — the assertion is the diff. {@code info.version} is
 * pinned to {@code 0} in the test properties, so the file changes only with the API.
 */
@QuarkusTest
public class OpenApiSchemaExportTest {

  @ConfigProperty(name = "quarkus.http.non-application-root-path")
  String nonApplicationRootPath;

  @Test
  public void exportOpenApiSchema() throws Exception {
    String schema =
        given()
            .when()
            .get(nonApplicationRootPath + "/openapi")
            .then()
            .statusCode(200)
            .extract()
            .asString();

    Path docsDir = Paths.get("../docs");
    if (!Files.exists(docsDir)) {
      Files.createDirectories(docsDir);
    }
    String header =
        "# THIS FILE IS GENERATED BY OpenApiSchemaExportTest — DO NOT EDIT MANUALLY.\n"
            + "# Run `./mvnw -pl service test -Dtest=OpenApiSchemaExportTest` to regenerate.\n";
    Files.writeString(docsDir.resolve("openapi.yml"), header + schema);
  }
}
